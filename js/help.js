export function openHelp() {
  const close = modal(h('div', { class: 'page' },
    h('div', { class: 'page-head' }, h('b', {}, '使用說明'), h('span', { class: 'spacer' }), h('button', { class: 'icon', onclick: () => close() }, '✕')),
    h('div', { class: 'page-body help-doc' },
      TOPICS.map(([title, text]) => h('details', {},
        h('summary', {}, title),
        h('div', { class: 'help-text' }, text.trim()))))), { cls: 'page-modal' });
}
